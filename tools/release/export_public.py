#!/usr/bin/env python3
r"""Export the public tree of BelthasarProject: the tracked files minus everything that comes from the game, scanned.

    python tools/release/export_public.py --out <dir> [--rom ROM] [--commit]

Copies every file `git ls-files` lists, except the patterns in EXCLUDE (ROM-derived data that the setup regenerates
from the user's own ROM: savestates and captures, src/data's tables, src/xlat's translated programs; and private or
stale material), into <dir> (which must not exist or be empty, and must be outside this repository). Then runs
tools/release/scan_rom_leaks.py and tools/release/scan_dialogue.py over <dir> with the ROM and, when present,
ct_assets.dat and the src/data tables as corpora, so a table that slipped through is caught by its bytes, not only by
its name. With --commit, `git init` + one commit (the public repository starts with a fresh history; see
docs/DECISIONS.md).

Prints what it left out, by pattern, and the scanner's verdict; exits 1 unless the tree is clean.
"""
import argparse
import fnmatch
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

EXCLUDE = [
    # generated from the user's ROM by tools/setup.py -- never published
    ('saves/*', 'savestates and captures (the game\'s RAM): rebuilt by tools/recipes.py'),
    ('*.state', 'savestates'), ('*.lakewram', 'WRAM captures'), ('*.wram', 'WRAM captures'),
    ('*.raw', 'oracle frame/VRAM dumps'), ('*.spr', 'captured sprites'), ('*.srm', 'battery saves'),
    ('*.sfc', 'the ROM'), ('*.smc', 'the ROM'), ('*.dat', 'the extracted assets'),
    ('src/data/*.h', 'tables extracted or captured from the game: generated by tools/setup.py'),
    ('src/xlat/*.c', 'ROM programs translated instruction by instruction: generated by tools/setup.py'),
    ('disasm/notes/*.asm', 'raw disassembly listings'),
    # binaries fetched at build time
    ('*.dll', 'fetched by tools/get_sdl2.ps1'), ('*.exe', 'build output'),
    # private or stale
    ('MEMORY.md', 'the old navigation index (superseded by README.md and docs/)'),
    ('regress_*.txt', 'old suite logs'), ('build_out*.txt', 'old build logs'), ('*.log', 'logs'),
]


KEEP = {                                         # files EXCLUDE would match that are published by name
    'ct_mapedits.dat': "the owner's painted world-map cells (tools/map_editor.py): block numbers per cell, no byte of "
                       "the game",
}


def excluded(path):
    if path in KEEP:
        return None
    for pat, why in EXCLUDE:
        if fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(os.path.basename(path), pat):
            return pat
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', required=True)
    ap.add_argument('--rom')
    ap.add_argument('--commit', action='store_true')
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    if out.startswith(ROOT + os.sep) or out == ROOT:
        sys.exit('export: --out must be outside the repository')
    if os.path.exists(out) and os.listdir(out):
        sys.exit('export: %s is not empty' % out)
    files = subprocess.run(['git', 'ls-files', '-z'], cwd=ROOT, capture_output=True).stdout.decode().split('\0')
    left, kept = {}, 0
    for f in filter(None, files):
        pat = excluded(f)
        if pat:
            left[pat] = left.get(pat, 0) + 1
            continue
        src = os.path.join(ROOT, f)
        if not os.path.isfile(src):
            continue
        dst = os.path.join(out, f)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        kept += 1
    print('export: %d files -> %s' % (kept, out))
    for pat, why in EXCLUDE:
        if pat in left:
            print('  left out %4d  %-22s %s' % (left[pat], pat, why))
    corpora = []
    for c in (os.path.join(ROOT, 'ct_assets.dat'), os.path.join(ROOT, 'src', 'data')):
        if os.path.exists(c):
            corpora += ['--corpus', c]
    scan = [sys.executable, os.path.join(ROOT, 'tools', 'release', 'scan_rom_leaks.py'), out] + corpora
    if a.rom:
        scan += ['--rom', a.rom]
    r = subprocess.run(scan, cwd=ROOT)
    r2 = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'release', 'scan_dialogue.py'), out]
                        + (['--rom', a.rom] if a.rom else []), cwd=ROOT)
    r = r if r.returncode else r2
    if r.returncode:
        print('export: NOT CLEAN -- nothing may be published from %s' % out)
        return 1
    if a.commit:
        subprocess.run(['git', 'init', '-q', '-b', 'main'], cwd=out, check=True)
        subprocess.run(['git', 'add', '-A'], cwd=out, check=True)
        ignored = subprocess.run(['git', 'ls-files', '--others', '--ignored', '--exclude-standard'], cwd=out,
                                 capture_output=True, text=True).stdout.split()
        if ignored:                                   # the public .gitignore would silently drop a file the tree uses
            print('export: the exported .gitignore ignores %d exported file(s): %s' % (len(ignored), ', '.join(ignored)))
            return 1
        msg = ('BelthasarProject: initial public tree\n\n'
               'A native C re-implementation of Chrono Trigger (SNES, USA), checked against the original running in an\n'
               'embedded SNES core. No part of the game is included: python tools/setup.py --rom <your dump> generates\n'
               'everything that comes from it. See README.md and docs/.\n\n'
               'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>')
        subprocess.run(['git', 'commit', '-q', '-m', msg], cwd=out, check=True)
        print('export: committed a fresh history in %s' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
