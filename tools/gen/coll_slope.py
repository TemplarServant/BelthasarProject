#!/usr/bin/env python3
"""The field collision's slope tables, read from the ROM into src/data/coll_slope.h.

    python tools/gen/coll_slope.py [out.h]      (default src/data/coll_slope.h)

C0/9AD3's slope evaluation (C0/9AF8-9B40, disasm/notes/collision.md; src/collision.c) indexes three 22-byte tables by
(shape - 2), for the slope shapes 2..0x17:
  C0/9BF5  bit 7 = negate X after the shift (EOR #$FF); bits 0-6 = the LSR count (1..3)
  C0/9C0B  the 8-bit constant ADDed after the shift
  C0/9C21  the EOR sign (00 keep / FF invert)
(HiROM file offsets 0x9BF5 / 0x9C0B / 0x9C21.) As ROM bytes they live with the other generated tables, which a
data-free build loads from the player's pack (docs/ROM.md).
"""
import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
N = 22
TABLES = (('ctCollSlopeBF5', 0x9BF5, 'C0/9BF5: bit 7 = negate X after the shift; bits 0-6 = the LSR count'),
          ('ctCollSlopeC0B', 0x9C0B, 'C0/9C0B: the constant added after the shift'),
          ('ctCollSlopeC21', 0x9C21, 'C0/9C21: the EOR sign (00 keep / FF invert)'))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'src', 'data', 'coll_slope.h')
    rom = _romlib.load(os.path.join(ROOT, 'Chrono_Trigger_USA_SNES.sfc'))
    lines = ['// GENERATED by tools/gen/coll_slope.py -- do not edit. The field collision\'s slope tables (C0/9AD3).',
             '#ifndef CT_COLL_SLOPE_H', '#define CT_COLL_SLOPE_H', '#include <stdint.h>',
             '#define CT_COLL_SLOPE_N %d' % N]
    for name, off, note in TABLES:
        lines.append('// %s' % note)
        lines.append('static const uint8_t %s[CT_COLL_SLOPE_N] = {' % name)
        lines.append('  ' + ','.join('0x%02X' % b for b in rom[off:off + N]) + ' };')
    lines.append('#endif')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('coll_slope: 3 x %d bytes (C0/9BF5, 9C0B, 9C21) -> %s' % (N, os.path.relpath(out, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
