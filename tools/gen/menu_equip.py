# Bake the EQUIP screen's ROM data into src/data/menu_equip.h, so the menu stays ROM-free.
# Derived in disasm/notes/menu2_equip_change.md; every table below is read straight out of the ROM
# at the address named, and the three ITEM PROPERTY PAGES are REBUILT here exactly the way the menu
# open builds them in RAM (C2/98B5 -> C2/9906 -> C2/992B -> C2/994C):
#
#   C2/8881(id)  class = the first k with id < C2/88A7[k+1]      (C2/88A7 = 00 5A 7B 94 BC F2)
#   C2/88AD      X  = FF/CF0E[class] + off * FF/CF18[class]      -> the "A" record, bank $CC
#   C2/88D8      X2 = FF/CF1D[class] + off * FF/CF27[class]      -> the "B" record, bank $CC
#   1. for id 0..0xF1 : $7A00[id] = CC:0003+X ; $7B00[id] = CC:0004+X
#   2. clear $7A00[0xBC..0xF1] (C2/9906) and $7B00[0x94..0xF1] (C2/9918)  -- MVN copies A+1 bytes
#   3. for id 0x94..0xBB : if (CC:0001+X2 & 0x40) $7B00[id] = CC:0002+X2   <- X2, and it STARTS at 0x94
#   4. for id 0..0x93 : $7C00[id] = CC:0000+X2
#
# Validated against a live oracle page (a --peek .wram of an open menu): 0 mismatches on all three.
import sys, os

ROM = open("Chrono_Trigger_USA_SNES.sfc", "rb").read()
def r8(a):  return ROM[a]
def r16(a): return ROM[a] | (ROM[a + 1] << 8)

CLS  = [r8(0x288A7 + i) for i in range(6)]                 # C2/88A7 class boundaries
CF0E = [r16(0x3FCF0E + i * 2) for i in range(5)]           # FF/CF0E "A" record bases (bank $CC)
CF18 = [r8(0x3FCF18 + i) for i in range(5)]                # FF/CF18 "A" strides
CF1D = [r16(0x3FCF1D + i * 2) for i in range(5)]           # FF/CF1D "B" record bases
CF27 = [r8(0x3FCF27 + i) for i in range(5)]                # FF/CF27 "B" strides

def locate(idv):
    k = 0
    while k < 5 and idv >= CLS[k + 1]: k += 1
    off = idv - CLS[k]
    return CF0E[k] + off * CF18[k], CF1D[k] + off * CF27[k]

mask = bytearray(0xF2); bonus = bytearray(0xF2); power = bytearray(0x94)
for i in range(0xF2):
    X, X2 = locate(i)
    mask[i]  = ROM[0x0C0000 + X + 3]
    bonus[i] = ROM[0x0C0000 + X + 4]
for i in range(0xBC, 0xF2): mask[i] = 0      # MVN copies A+1 bytes: $7ABC..$7AF1 (C2/9906)
for i in range(0x94, 0xF2): bonus[i] = 0     # ... and $7B94..$7BF1 (C2/9918)
for i in range(0x94, 0xBC):                  # C2/9924: the loop STARTS at 0x94 and runs to 0xBB
    X, X2 = locate(i)
    if ROM[0x0C0000 + X2 + 1] & 0x40: bonus[i] = ROM[0x0C0000 + X2 + 2]
for i in range(0x94):
    X, X2 = locate(i)
    power[i] = ROM[0x0C0000 + X2]

def emit(f, name, data, note):
    f.write("// %s\n" % note)
    f.write("static const uint8_t %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write("  " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")

def emit16(f, name, words, note):
    f.write("// %s\n" % note)
    f.write("static const uint16_t %s[%d] = {\n" % (name, len(words)))
    for i in range(0, len(words), 8):
        f.write("  " + ",".join("0x%04X" % w for w in words[i:i + 8]) + ",\n")
    f.write("};\n")

with open("src/data/menu_equip.h", "w") as f:
    f.write("// GENERATED by tools/gen/menu_equip.py -- do not edit. The EQUIP screen's ROM data,\n")
    f.write("// extracted once so the runtime menu needs no .sfc. See the script header + the dossier\n")
    f.write("// disasm/notes/menu2_equip_change.md for every address.\n")
    f.write("#ifndef CT_MENU_EQUIP_H\n#define CT_MENU_EQUIP_H\n#include <stdint.h>\n")
    emit(f, "ctEqMask", mask,
         "$7E:7A00 -- the item's EQUIP-BY-CHARACTER bitmask; equippable(id,char) <=> mask[id] & (0x80>>charId) (C2/93AF + FF/F9BB)")
    emit(f, "ctEqBonusIdx", bonus, "$7E:7B00 -- the item's bonus-set index into CC/29D7 (0 = no bonus)")
    emit(f, "ctEqPower", power, "$7E:7C00 -- the gear 'power' byte: weapon Atk source, armour Def source, AND the list sort key")
    emit16(f, "ctEqBonusSet", [r16(0x0C29D7 + i * 2) for i in range(0x100)],
           "CC/29D7 -- bonus set: low byte = a stat MASK walked from bit7, high byte = the amount added")
    emit(f, "ctEqStatOff", ROM[0x3FCF2C:0x3FCF33],
         "FF/CF2C -- mask bit k -> the stat's offset inside the sheet's +0x0B..+0x11 block")
    emit(f, "ctEqStatCap", ROM[0x3FCF33:0x3FCF3A], "FF/CF33 -- per-k cap (note: indexed by k, NOT by the offset)")
    emit(f, "ctEqRange", ROM[0x289DC:0x289E4],
         "C2/89DC -- INTERLEAVED [lo,hi) per gear slot: Weapon [00,5A) Helm [7B,94) Armor [5A,7B) Accessory [94,BC)")
    emit(f, "ctEqSheetOff", ROM[0x2A4AB:0x2A4AF], "C2/A4AB -- gear slot -> sheet offset: Weapon +29, Helm +27, Armor +28, Accessory +2A")
    emit16(f, "ctEqAyla", [r16(0x0C2D69 + i * 2) for i in range(100)], "CC/2D69 -- Ayla's per-LEVEL attack term (C2/91DB case 5)")
    f.write("#endif\n")

print("wrote src/data/menu_equip.h")
print("  C2/88A7", [hex(v) for v in CLS])
print("  ctEqRange     ", ROM[0x289DC:0x289E4].hex(' '), "(expect 00 5a 7b 94 5a 7b 94 bc)")
print("  ctEqSheetOff  ", ROM[0x2A4AB:0x2A4AF].hex(' '), "(expect 29 27 28 2a)")
print("  ctEqStatOff   ", ROM[0x3FCF2C:0x3FCF33].hex(' '), "(expect 00 02 01 04 05 03 06)")
print("  ctEqStatCap   ", ROM[0x3FCF33:0x3FCF3A].hex(' '), "(expect 63 10 63 63 63 63 63)")
print("  mask[01]=%02X (Wood Sword, Crono only) power[05]=%d (Red Katana)" % (mask[1], power[5]))

# Optional cross-check against a live oracle page, when one is lying around.
import glob
for p in sorted(glob.glob("scratchpad/menu/*.wram")):
    w = open(p, "rb").read()
    if len(w) < 0x8000 or not any(w[0x7C00:0x7C94]): continue
    bad = lambda pg, base, n: sum(1 for i in range(n) if pg[i] != w[base + i])
    print("  vs %s: 7A00 %d/242, 7B00 %d/242, 7C00 %d/148 mismatches"
          % (p, bad(mask, 0x7A00, 0xF2), bad(bonus, 0x7B00, 0xF2), bad(power, 0x7C00, 0x94)))
    break
