# Bake the ITEM/EQUIPMENT DESCRIPTION strings into src/data/menu_desc.h.
#
# THE POINT: the port used to GENERATE these lines -- menu.c's mItemDesc built "Restores %d HP" out
# of the baked effect record, and CtMenuEquipDesc built "Power +2" out of a bonus mask, with a
# comment claiming the ROM has no stored string. It has one. C2/F2F3, the description stager, does:
#
#   2F308  STA $020C          ; the item id
#   2F317  LDX #2EB1 / STX $020D
#   2F31D  LDA #CC   / STA $020F      -> the 24-bit source pointer $CC:2EB1
#   2F32D  JSR C2/FA49                -> render
#
# so $CC:2EB1 is a table of 16-bit LOCAL pointers into bank $CC, indexed by item id.
#
# THE ENTRY COUNT IS NOT ASSUMED, IT IS READ OUT OF THE DATA: the smallest pointer in the table is
# $3095, and 0x2EB1 + 242*2 == 0x3095 exactly -- i.e. the strings start immediately after the table,
# so the table is exactly 242 entries (ids $00..$F1, which is also the item id space).
import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
import sys, os
sys.path.insert(0, "assets")
import text as CTTEXT                      # the repo's own dictionary decoder

ROM = _romlib.load("Chrono_Trigger_USA_SNES.sfc")
SUBS = CTTEXT.load_dict(ROM)

BASE = 0x0C2EB1                            # CC/2EB1, HiROM file offset
N = 242

ptrs = [ROM[BASE + i * 2] | (ROM[BASE + i * 2 + 1] << 8) for i in range(N)]
assert min(ptrs) == (BASE & 0xFFFF) + N * 2, (
    "the table does not end where its first string begins -- N is wrong: min ptr %04X, table end %04X"
    % (min(ptrs), (BASE & 0xFFFF) + N * 2))

# namesub=True keeps the CLOSING quote 0xE2 apart from the opening 0xE1 (U+201D; two glyphs in the ROM's font -- 32 of
# these lines close a quote: '"Power" +1' is E1 .. E2). No item description holds a name or number code (asserted).
desc = [CTTEXT.decode_string(ROM, 0x0C0000 + p, SUBS, namesub=True) for p in ptrs]
assert not any('\x01' in s for s in desc)
W = max(len(s) for s in desc) + 1


def c(s):
    # the closing quote as its raw CT code 0xE2 (the VWF's cGlyph renders 0xA0..0xF3 as the font's own glyphs); the
    # `""` ends the hex escape so a following hex digit is not swallowed
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\u201d', '\\xE2""') + '"'


out = ['// GENERATED by tools/gen/menu_desc.py -- do not edit.',
       '// The ROM\'s STORED item/equipment description strings: the pointer table at CC/2EB1',
       '// (16-bit local pointers into bank $CC), indexed by item id, staged by C2/F2F3 through',
       '// $020C/$020D-$020F and rendered by C2/FA49. %d entries ($00..$F1), %d of them non-empty.' % (N, sum(1 for s in desc if s)),
       '// An EMPTY string is the ROM\'s own answer, not a gap: 137 ids describe nothing.',
       '#ifndef CT_MENU_DESC_H', '#define CT_MENU_DESC_H', '',
       'static const char ctItemDesc[%d][%d] = {' % (N, W)]
for i in range(0, N, 2):
    row = '  ' + ', '.join(c(desc[j]) for j in range(i, min(i + 2, N)))
    out.append(row + ',')
out += ['};', '', '#endif']
os.makedirs("src/data", exist_ok=True)
open("src/data/menu_desc.h", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

print("wrote src/data/menu_desc.h  (%d x %d)" % (N, W))
print("  non-empty %d, distinct %d, longest %r" % (sum(1 for s in desc if s), len(set(s for s in desc if s)),
                                                   max(desc, key=len)))
for i in (0xBD, 0xC6, 0xC8, 0xCD, 0x95, 0x96, 0x98, 0xB6, 0xD6):
    print("  %02X -> %r" % (i, desc[i]))
