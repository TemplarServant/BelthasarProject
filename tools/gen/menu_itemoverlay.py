#!/usr/bin/env python3
"""src/data/menu_itemoverlay.h -- the Item screen's target-select window, from the oracle's VRAM.

The window is C2/ED31's list $FF:C0A6 `04` command (style 8B, attribute 03, at (2,32), 14 x 16): BG2 cells written
into the map at VRAM word $6000 (record FBF8: $3E00 -> $6000, 64 rows). The style has bit 7 set (not the player's
window colour), so its cells are a constant; C2/AFB5's offset-per-tile rows show them at screen columns 16-28, lines
80-207 (menu.c).

The capture: tools/menu_audit_cmp.py's `itemuse` drive (X, R to Item, A, Down to the Tonic, A pick, A use -> the target
window), its oracle frame 172 (+2, the drive's shift): the overlay is up. From the recipe grupo_3_mapa (loc 082, the
party Crono/Lucca/Frog, a Tonic in bag slot 1 -- the drive's own layout, without its pokes).
saves/battle_re/party3_field.state with the pokes $2401 = BD, $2501 = 03 (three Tonics) gives the same file.

    python tools/gen/menu_itemoverlay.py [--state S [--poke 2401=BD,2501=03]] [--vram V] [--out src/data/menu_itemoverlay.h]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctgen import ROOT, recipe, peek, scratch  # noqa: E402

# menu_audit_cmp.py itemuse: X@4, R@50, A@80, Down@110, A@130, A@150, A@170; peeked at 172 + 2
DRIVE = '0:4,200:2,0:44,80:2,0:28,100:2,0:28,20:2,0:18,100:2,0:18,100:2,0:18,100:2,0:2'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--state', help='the start state instead of the recipe (saves/battle_re/party3_field.state)')
    ap.add_argument('--poke', help='PEEK_POKE for --state, e.g. 2401=BD,2501=03')
    ap.add_argument('--vram', help='an existing VRAM dump of an overlay frame (skips the oracle)')
    ap.add_argument('--out', default=os.path.join('src', 'data', 'menu_itemoverlay.h'))
    a = ap.parse_args()
    if a.vram:
        vpath = a.vram
    else:
        env = {'PEEK_POKE': a.poke} if a.poke else None
        vpath = peek(a.state or recipe('grupo_3_mapa'), scratch('menu_itemoverlay'), DRIVE, env=env) + '.raw.vram'
    vram = open(vpath, 'rb').read()
    BASE = 0x6000 * 2
    rows = []
    for r in range(32, 48):
        row = []
        for c in range(2, 16):
            o = BASE + (r * 32 + c) * 2
            w = vram[o] | (vram[o + 1] << 8)
            if not 0x3DC <= (w & 0x3FF) <= 0x3EF:
                sys.exit('menu_itemoverlay: not a window tile at (%d,%d): %04X -- the overlay is not up' % (c, r, w))
            row.append(w)
        rows.append(row)
    out = ['// menu_itemoverlay.h -- GENERATED by tools/_gen_item_overlay.py from the oracle VRAM of the Item target overlay.',
           '// The BG2 cells of $FF:C0A6\'s `04 8B 03 02 20 0E 10` window (style 8B, attribute 03, at (2,32), 14 x 16);',
           '// C2/AFB5\'s offset-per-tile rows show them at screen columns 16-28, lines 80-207 (menu.c).',
           '#ifndef CT_MENU_ITEMOVERLAY_H', '#define CT_MENU_ITEMOVERLAY_H', '#include <stdint.h>',
           'static const uint16_t ctItemOverlayWinTM[16][14] = {']
    for row in rows:
        out.append('  { ' + ', '.join('0x%04X' % w for w in row) + ' },')
    out += ['};', '#endif', '']
    path = a.out if os.path.isabs(a.out) else os.path.join(ROOT, a.out)
    open(path, 'w', newline='\n').write('\n'.join(out))
    print('wrote %s (16 x 14 cells)' % a.out)


if __name__ == '__main__':
    main()
