#!/usr/bin/env python
# Generator for the stage-1 GATO pose-engine data. Emits three tracked headers from the ROM + an oracle WRAM
# sheet dump:
#   src/data/animeng_e3_gato.h     -- E3 assembly records (positions + cell-words), base $E30000 stride 0x78
#   src/data/animeng_e4_gato.h     -- per-facing pose windows (the oracle's $9907[6] cycles + dwells)
#   src/data/animeng_sheet_gato.h  -- the $7F8000 sprite sheet (a fixture from oracle WRAM; open items O3/C5)
#
# Sources:
#   ROM   = repo-root Chrono_Trigger_USA_SNES.sfc (unheadered 4MB, HiROM).
#   SHEET = $7F8000 region of gato_noatk.state's WRAM, captured via:
#             ct.exe --peek gato_noatk.state g.raw --btnscript "0:70"
#           then g.raw.wram[0x18000:] (=$7F8000). A copy is saves/battle_re/gato_sheet_noatk_f70.wram
#           (a private capture); any in-battle WRAM of the fight serves.
#   The E3 record layout ([48 cell-words +0x00][12 dx,dy +0x60]): disasm/notes/battle_anim_engine.md
#   ADDENDUM 1 (contradiction C1).
#   The per-facing windows are the oracle's $9907[6] cursor cycles
#   (gato_noatk idle; corpus/crono_far{left,right} walks; gato_moving_lake up walk).
import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
ROM = _romlib.load(os.path.join(ROOT, "Chrono_Trigger_USA_SNES.sfc"))
# The sheet is decompressed into $7F8000 at the battle's boot and does not change through the fight: any in-battle
# WRAM of GATO's fight serves (the recipe gato_inbattle, tools/recipes/; a raw 128 KB .wram dump also works).
SHEET_WRAM = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "recipes", "gato_inbattle.state")

E3_BASE = (0xE3 - 0xC0) << 16       # $E30000  (= $1C78[pidx] for GATO on the oracle)
STRIDE  = 0x78
N_REC   = 0x20                       # stage-1 idle/walk 0x00..0x0B + stage-2 song sway 0x0D..0x0F +
                                     #   attack blocks UP 0x10-13 / FRONT 0x14-17 / LEFT 0x18-1B / RIGHT 0x1C-1F
SHEET_N = 0x160                      # srcTiles 0..0x15F (the RIGHT attack block idx0x1D-1F reaches 0x158)

def sext(b): return b - 256 if b >= 0x80 else b
def rec(n): return ROM[E3_BASE + n*STRIDE : E3_BASE + n*STRIDE + STRIDE]
def positions(r): return [(sext(r[0x60+2*i]), sext(r[0x60+2*i+1])) for i in range(12)]
def cellwords(r): return [r[2*i] | (r[2*i+1] << 8) for i in range(48)]

# ---- per-facing pose windows (resolved $9907[6] cycles; idx + dwell frames) ----
# facing: 0=UP 1=DOWN(idle) 2=LEFT 3=RIGHT  (ctBattleFaceTab / $96DE)
WINDOWS = {
    0: ("UP",         [(0x01,33),(0x02,27),(0x01,33),(0x00,27)]),  # gato_moving_lake RETURN walk
    1: ("DOWN_idle",  [(0x04,27),(0x03,33),(0x04,27),(0x05,33)]),  # gato_noatk STEADY claw-swap (period 120, 87 rest/33 swap)
    2: ("LEFT",       [(0x08,33),(0x07,27),(0x06,27),(0x07,33)]),  # corpus/crono_farleft leg-cycle
    3: ("RIGHT",      [(0x0B,33),(0x0A,27),(0x09,27),(0x0A,33)]),  # corpus/crono_farright leg-cycle
}

def w_e3():
    o = ["// GENERATED by tools/gen/animeng_gato.py -- do not edit.",
         "// GATO E3 sprite-ASSEMBLY records (bank E3, base $E30000, stride 0x78), stage-1 indices 0x00-0x0B.",
         "// Layout per battle_anim_engine.md ADDENDUM 1 (contradiction C1 RESOLVED): each 0x78 record is",
         "//   [+0x00 .. +0x60] 48 x 16-bit CELL-WORDS (srcTile[0:10] | Hflip[bit14]; word 0 = blank) -> tile GATHER",
         "//   [+0x60 .. +0x78] 12 signed (dx,dy) pairs -> OAM cell POSITIONS (tile order 0x68 6A 6C 6E 80 82 84 86 88 8A 8C 8E)",
         "// The cell-word RASTER order maps 1:1 to VRAM 8x8 tiles 0x68-0x6F,0x78-0x7F,0x80-0x87,0x90-0x97,0x88-0x8F,0x98-0x9F.",
         "#ifndef CT_ANIMENG_E3_GATO_H",
         "#define CT_ANIMENG_E3_GATO_H",
         "#include <stdint.h>",
         "",
         "typedef struct { int8_t dx, dy; } CtAnimengPos;              // OAM cell offset from the live foot",
         "typedef struct { CtAnimengPos pos[12]; uint16_t cw[48]; } CtAnimengE3Rec;",
         "#define CT_ANIMENG_E3_GATO_N 0x%02X" % N_REC,
         "static const CtAnimengE3Rec ctAnimengE3Gato[CT_ANIMENG_E3_GATO_N] = {"]
    for n in range(N_REC):
        r = rec(n); ps = positions(r); cw = cellwords(r)
        pos = ' '.join("{%d,%d}," % (dx,dy) for dx,dy in ps)
        o.append("  { // idx 0x%02X" % n)
        o.append("    { %s }," % pos)
        cws = ["0x%04X," % w for w in cw]
        for i in range(0, 48, 12):
            o.append("    " + ' '.join(cws[i:i+12]) + ("  // cw" if i==0 else ""))
        o.append("  },")
    o += ["};", "#endif", ""]
    return '\n'.join(o)

def w_e4():
    o = ["// GENERATED by tools/gen/animeng_gato.py -- do not edit.",
         "// GATO resolved per-facing POSE WINDOWS = the oracle $9907[6] cursor cycles (the assembly index the",
         "// enemy pose tick C1/3360 emits per cursor 0..3, with its dwell in frames). These are the O4/O7",
         "// INTERIM (the raw E4 ptrA `04 14 FF 00`+ptrB timing + the $97D9->$967B remap produce them; the remap",
         "// is the standing open item). Captured this session: idle=gato_noatk steady (period 120, 27/33/27/33);",
         "// walk L/R=corpus/crono_far{left,right}; UP=gato_moving_lake RETURN walk. facing: 0=UP 1=DOWN 2=LEFT 3=RIGHT.",
         "#ifndef CT_ANIMENG_E4_GATO_H",
         "#define CT_ANIMENG_E4_GATO_H",
         "#include <stdint.h>",
         "",
         "typedef struct { uint8_t idx, dwell; } CtAnimengStep;        // E3 assembly index + dwell (frames)",
         "typedef struct { CtAnimengStep step[4]; } CtAnimengWindow;   // 4-cursor loop (wrap at 4)",
         "// indexed by facing (0..3)",
         "static const CtAnimengWindow ctAnimengWinGato[4] = {"]
    for f in range(4):
        name, steps = WINDOWS[f]
        s = ' '.join("{0x%02X,%d}," % (i,d) for i,d in steps)
        o.append("  { { %s } },  // facing %d %s" % (s, f, name))
    o += ["};", ""]
    # ---- stage 2: the attack (rear-up + strike per facing), front tile stream, and song windows ----
    # From the ROM's E3 records; they match the corpus captures (crono_{left,right,up}/gato_mid): the position
    # sub-block (+0x60) equals the capture's cells relative to the live foot, and the cell-word gather (+0x00)
    # from the $7F8000 sheet equals the capture VRAM. facing 0=UP 1=DOWN/front 2=LEFT 3=RIGHT.
    o += [
      "// STAGE 2 (attack/hurt/song) -- the E3 assembly INDICES the CD action script selects, pinned this",
      "// session from the ROM + the corpus captures + the retired bakes (all byte-exact). See w_e4()/generator.",
      "typedef struct { uint8_t rear, strike, strikeAt; } CtAnimengGatoAtk;  // rear-up idx, strike idx, rel of flip",
      "// per FACING (0=UP 1=FRONT 2=LEFT 3=RIGHT). FRONT (1) is the fixed-OAM tile-stream (ctAnimengGatoFrontSwing);",
      "// UP holds its rear-up (no side-strike capture -- no PC above GATO). LEFT/RIGHT lunge to their strike idx.",
      "static const CtAnimengGatoAtk ctAnimengGatoAtk[4] = {",
      "  { 0x11, 0x11, 49 },  // UP    rear-up 0x11 == corpus U_f195 + atkface U_rear (42/42)",
      "  { 0x15, 0x15, 49 },  // FRONT rear-up 0x15 == corpus F_f125 + GS1 (40/40); tile-stream via FrontSwing",
      "  { 0x19, 0x1A, 20 },  // LEFT  rear-up 0x19 -> lunge strike 0x1A (35/35, 41/41; strikeAt corpus 1.3)",
      "  { 0x1D, 0x1E, 21 },  // RIGHT rear-up 0x1D -> claw-extend strike 0x1E (35/35, 41/41; strikeAt corpus 1.3)",
      "};",
      "// FRONT attack-A claw-swipe tile-stream: GS1/GS2/GS3 map BYTE-EXACT to E3 0x15/0x16/0x17 (same fixed OAM,",
      "// different cell-words). [a,b) = rel window (rel to rear-up dispatch), from the retired ctGatoSwipeKf.",
      "typedef struct { uint8_t idx, a, b; } CtAnimengGatoSwing;",
      "static const CtAnimengGatoSwing ctAnimengGatoFrontSwing[3] = { {0x15,1,24}, {0x16,24,30}, {0x17,30,49} };",
      "// HURT/RECOIL pose (battle_anim_polish2.md ITEM 1): a DISTINCT arms-up recoil assembly (raised anchor",
      "// ~12px, its own 0x100-0x126 tiles) held ~15f at the incoming PC strike. Facing-invariant (same 0x0C",
      "// regardless of facing). The pose SUPPLIES the recoil -- GATO's live foot is CONSTANT (no knockback).",
      "#define CT_ANIMENG_GATO_HURT           0x0C",
      "#define CT_ANIMENG_GATO_HURT_DWELL     15",
      "// attack-B FLURRY (battle_anim_polish2.md ITEM 2): fist-out <-> retract, 8f each, 6 cycles, over rel",
      "// +26..+117 (windup = the facing's idle-rest for rel 0..25). FACING-DISPATCHED pose pair: FRONT (facing 1)",
      "// 0x16/0x17, RIGHT (facing 3) 0x1E/0x1F (both within their block, cross-validated vs the oracle this",
      "// session). UP/LEFT are non-canonical for the GATO formation (no PC above/left) -> un-captured, left 0",
      "// (field.c falls those facings back to the directional rear->strike, never a fabricated flurry).",
      "#define CT_ANIMENG_GATO_FLURRY_DWELL   8   // frames per pose (was the misread 3+4/cycle)",
      "#define CT_ANIMENG_GATO_FLURRY_CYCLES  6   // fist<->retract cycles",
      "#define CT_ANIMENG_GATO_FLURRY_WINDUP  26  // rel of the first fist (0..25 = idle-rest windup)",
      "typedef struct { uint8_t fist, retract, windup; } CtAnimengGatoFlurry;  // per-facing pose pair + windup idle",
      "static const CtAnimengGatoFlurry ctAnimengGatoFlurryPair[4] = {",
      "  { 0x00, 0x00, 0x00 },  // facing 0 UP    -- non-canonical (fallback: directional rear->strike)",
      "  { 0x16, 0x17, 0x04 },  // facing 1 FRONT (dossier 2.1: 0x16 fist / 0x17 retract; windup idle-rest 0x04)",
      "  { 0x00, 0x00, 0x00 },  // facing 2 LEFT  -- non-canonical (fallback: directional rear->strike)",
      "  { 0x1E, 0x1F, 0x0A },  // facing 3 RIGHT (dossier 2.2: 0x1E fist / 0x1F retract; windup right-idle 0x0A)",
      "};",
      "// SONG: GATO holds his front idle-rest (arms-out) + a gentle 4-phase 068/06A claw SWAY (corpus 2.1). The",
      "// sway rep frame song_f470/f500 == E3 0x0E (12/12 cells + VRAM). Cycle 0x0D->0x0E->0x0F->0x0E, dwell 15,",
      "// active only in the lit window rel 42..236 (co-timed with the spotlight); else arms-out (idle-rest 0x04).",
      "#define CT_ANIMENG_GATO_SONG_ARMSOUT   0x04",
      "#define CT_ANIMENG_GATO_SONG_SWAY_DWELL 15",
      "#define CT_ANIMENG_GATO_SONG_LIT0      42",
      "#define CT_ANIMENG_GATO_SONG_LIT1      236",
      "static const uint8_t ctAnimengGatoSongSway[4] = { 0x0D, 0x0E, 0x0F, 0x0E };",
      "",
    ]
    o += ["#endif", ""]
    return '\n'.join(o)

def w_sheet():
    if not os.path.exists(SHEET_WRAM):
        sys.exit("MISSING sheet wram: %s\n  capture: ct.exe --peek gato_noatk.state g.raw --btnscript \"0:70\"\n  then cp g.raw.wram %s" % (SHEET_WRAM, SHEET_WRAM))
    wram = open(SHEET_WRAM, "rb").read()
    if len(wram) != 0x20000:                          # a LakeSnes state: WRAM at +69 of the (CTLS-unwrapped) payload
        wram = (wram[16:] if wram[:4] == b"CTLS" else wram)[69:69 + 0x20000]
    sheet = wram[0x18000 : 0x18000 + SHEET_N*0x20]   # $7F8000
    o = ["// GENERATED by tools/gen/animeng_gato.py -- do not edit.  *** INTERIM FIXTURE ***",
         "// GATO sprite SHEET: WRAM $7F8000 (ptr $1C57[pidx]), tiles 0..0x%03X, 8x8 4bpp (0x20 B each)." % (SHEET_N-1),
         "// Captured from gato_noatk.state (front idle) -- the sheet is FIXED across facings (front==left==up,",
         "// verified this session), so ONE dump serves every GATO pose; facings differ only by which E3 cell-words",
         "// gather. The ROM->$7F8000 boot DECOMPRESSOR (keyed by enemy id 0x92) is the standing open (O3/C5); until",
         "// it is derived this baked dump is the sanctioned interim, exactly like ct_charbase.h.",
         "#ifndef CT_ANIMENG_SHEET_GATO_H",
         "#define CT_ANIMENG_SHEET_GATO_H",
         "#include <stdint.h>",
         "#define CT_ANIMENG_SHEET_GATO_N 0x%03X" % SHEET_N,
         "static const uint8_t ctAnimengSheetGato[CT_ANIMENG_SHEET_GATO_N][32] = {"]
    for t in range(SHEET_N):
        b = sheet[t*0x20:(t+1)*0x20]
        o.append("  {" + ','.join("0x%02X"%x for x in b) + "},")
    o += ["};", "#endif", ""]
    return '\n'.join(o)

for fn, txt in [("animeng_e3_gato.h", w_e3()), ("animeng_e4_gato.h", w_e4()), ("animeng_sheet_gato.h", w_sheet())]:
    p = os.path.join(ROOT, "src", "data", fn)
    open(p, "w", newline="\n").write(txt)
    print("wrote %s (%d bytes)" % (p, len(txt)))
