#!/usr/bin/env python3
"""Bake the overworld anim sub-VM bytecode (ROM bank $C3) into src/data/ow_anim.h.

The sub-VM interpreter C2/0E1D runs bytecode whose pointer table is C3:E000 (op 0x30 of the object VM
stamps `+0B = C3:E000[id*2]`, `+0D = $C3`). world.c reads no ROM, so the reachable region is baked here,
like the menu's $CC name-table slice.

Region: C3:E000..C3:FFFF (8 KB). Walking all 256 pointer-table entries with the interpreter's advance rules
(op 4 = 4 bytes, ops 0/1/2/5 = 2, op 3 = a signed jump) touches C3:E14C..C3:FF04; the table itself is
C3:E000..E1FF. (The gull/boat objects run scripts at C3:F0F2 and C3:FA6D, past E000..EFFF.)

Run from the repo root: python tools/gen/ow_anim.py [rom] > src/data/ow_anim.h
"""
import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
import sys

ROM = sys.argv[1] if len(sys.argv) > 1 else 'Chrono_Trigger_USA_SNES.sfc'
BASE, SIZE = 0x03E000, 0x2000          # flat file offset of $C3:E000, 8 KB (to $C3:FFFF)

rom = _romlib.load(ROM)
blob = rom[BASE:BASE + SIZE]

print("// ow_anim.h - the overworld ANIM SUB-VM bytecode, verbatim from ROM $C3:E000..FFFF.")
print("// Generated by tools/gen/ow_anim.py -- DO NOT EDIT BY HAND.")
print("// Consumed by world.c's port of the interpreter C2/0E1D: the object's +0B/+0C pointer")
print("// (stamped from the table at $C3:E000 by object-VM op 0x30) indexes this blob, and the")
print("// handlers at C2/0E4A..0F34 read their operands from it.")
print("#ifndef CT_OW_ANIM_H")
print("#define CT_OW_ANIM_H")
print("#include <stdint.h>")
print("#define CT_OWANIM_BASE 0xE000u   /* the $C3 address the blob starts at */")
print("#define CT_OWANIM_SIZE 0x%Xu" % SIZE)
print("static const uint8_t ctOwAnimC3[CT_OWANIM_SIZE] = {")
for i in range(0, SIZE, 16):
    print("  " + ",".join("0x%02X" % b for b in blob[i:i + 16]) + ",")
print("};")
print("#endif")
