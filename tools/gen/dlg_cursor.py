#!/usr/bin/env python3
"""src/data/dlg_cursor.h -- the DIALOGUE DECISION CURSOR (the pointing hand), lifted out of an oracle frame.

CT's decision box (event ops 0xC0/0xC3/0xC4) marks the selected option with a small pointing HAND drawn into the
dialogue window itself -- not an OBJ (the oracle's OAM at the option page holds only the party sprites), and not the
menu's hand either (src/data/menu_itemdetail.h, OBJ tile 0x20: compared pixel by pixel, 63/138 -- another graphic).

METHOD -- the one the window bitmap itself came from: take a frame with the option page up and SUBTRACT the window
texture (saves/ct_window.bin, T_WINDOW -- tools/gen/ct_window.py, the asset stage, runs first). Every pixel of the
window's 80 rows maps 1:1 onto the frame (fb row = window row + 16 on a 240-row peek dump), so whatever differs inside
the cursor's cell IS the cursor. Pixels equal to the texture are transparent -- an edge pixel that happens to match the
window exactly would be dropped, which is why the cell is a fixed 16x12 box rather than the diff's bbox.

CAPTURE (Norstein Bekkler's lab, loc 1B2 -- its `C0 40 03` box has four options), from recipe truce_market (it stands
in for saves/truce_market.state):
  ct.exe --teleport 434 8 8 0 --from <truce_market> --out o434.state --frames 240
  ct.exe --peek o434.state o434e.raw --btnscript "10:8,0:6,100:6,0:180,100:6,0:60,100:6,0:60,100:6,0:120,100:6,0:120"
The cursor's cell in WINDOW space is (16,10)-(31,21): x 16 is one glyph cell left of the option text (the options are
indented six spaces = x 32), and row 10 is the first option line's glyph row. Port of tools/gen_dlgcursor.py (which
took the picture as a PNG; the PNG was the same 2x-downsampled framebuffer this reads directly).

    python tools/gen/dlg_cursor.py [--state S] [--window saves/ct_window.bin] [--out src/data/dlg_cursor.h]
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctgen import CT, ROM, ROOT, recipe, peek, scratch, rgb_of_fb  # noqa: E402

CELL_X, CELL_Y, CELL_W, CELL_H = 16, 10, 16, 12
FB_OFFSET = 16          # peek dumps are 240 rows; the box's top row 0 lands at fb y 16
DRIVE = '10:8,0:6,100:6,0:180,100:6,0:60,100:6,0:60,100:6,0:120,100:6,0:120'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--state', help='the start instead of recipe truce_market (e.g. saves/truce_market.state)')
    ap.add_argument('--window', default='saves/ct_window.bin')
    ap.add_argument('--out', default='src/data/dlg_cursor.h')
    a = ap.parse_args()
    start = os.path.abspath(a.state) if a.state else recipe('truce_market')
    lab = scratch('nm_o434.state')
    env = dict(os.environ, SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy', CT_ORACLE_LOGICAL='1')
    if os.path.exists(lab):
        os.remove(lab)
    p = subprocess.run([CT, ROM, '--teleport', '434', '8', '8', '0', '--from', start, '--out', lab, '--frames', '240'],
                       cwd=ROOT, env=env, capture_output=True, text=True, errors='replace')
    if not os.path.exists(lab):
        sys.exit('dlg_cursor: --teleport 434 wrote no state: %s' % (p.stdout + p.stderr)[-600:])
    fb = rgb_of_fb(peek(lab, scratch('nm_o434e'), DRIVE) + '.raw')

    w = open(a.window, 'rb').read()
    hgt, px = w[0], w[1:]
    if len(px) < 256 * hgt * 3:
        sys.exit('dlg_cursor: window bitmap truncated')
    rgba, opaque = [], 0
    for y in range(CELL_H):
        for x in range(CELL_W):
            wx, wy = CELL_X + x, CELL_Y + y
            o = (wy + FB_OFFSET) * 256 + wx
            o = tuple(fb[o * 3:o * 3 + 3])
            b = tuple(px[(wy * 256 + wx) * 3:(wy * 256 + wx) * 3 + 3])
            if o == b:
                rgba.append((0, 0, 0, 0))
            else:
                rgba.append((o[0], o[1], o[2], 255))
                opaque += 1
    if opaque < 40:
        sys.exit('dlg_cursor: only %d opaque pixels -- wrong frame or misaligned cell' % opaque)
    with open(a.out, 'w') as f:
        f.write('// GENERATED by tools/gen_dlgcursor.py -- do not hand-edit.\n')
        f.write('// The dialogue DECISION CURSOR (pointing hand), lifted from an oracle frame by\n')
        f.write('// subtracting the dialogue window texture (see the generator docstring for the\n')
        f.write('// capture). %dx%d, RGBA8888 row-major, alpha 0 = window shows through.\n' % (CELL_W, CELL_H))
        f.write('// Cell in window space: (%d,%d)-(%d,%d); %d opaque pixels.\n'
                % (CELL_X, CELL_Y, CELL_X + CELL_W - 1, CELL_Y + CELL_H - 1, opaque))
        f.write('#ifndef GEN_DLG_CURSOR_H\n#define GEN_DLG_CURSOR_H\n')
        f.write('#define DLGCURSOR_W %d\n#define DLGCURSOR_H %d\n' % (CELL_W, CELL_H))
        f.write('static const unsigned char dlgCursorRGBA[%d * %d * 4] = {\n' % (CELL_W, CELL_H))
        for y in range(CELL_H):
            row = rgba[y * CELL_W:(y + 1) * CELL_W]
            f.write('  ' + ','.join('%d,%d,%d,%d' % q for q in row) + ',\n')
        f.write('};\n#endif\n')
    print('wrote %s (%d opaque of %d)' % (a.out, opaque, CELL_W * CELL_H))


if __name__ == '__main__':
    main()
