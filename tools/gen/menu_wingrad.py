import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
# Bake the menu's window-gradient lists out of the ROM into src/data/menu_wingrad.h
# (disasm/notes/menu2_window_gradient.md).
#
# The dark menu windows are shaded by an HDMA channel over $2131/$2132 (CGADSUB + COLDATA): a 16-step
# ramp +8..-7 in 5-bit colour space, restarted and scaled to each window's height. The generator C2/86DD
# copies the 16 (CGADSUB, COLDATA) pairs at C2/8771 to $7E:9DE9 and walks a window list at $7E:9D99 of
# [kind, height] entries (kind 0 = flat, 1 = ramp, 0x80 = end). The lists are ROM data at $FF:BBF2,
# length-prefixed and back to back, copied to $7E:9D99 by the bank-FF->7E block copier C2/F362 (byte 0 is
# the length). Each ribbon hover writes one (C2:F376); an entered sub-screen keeps the hovered option's list.
#
# Regenerate:  python tools/gen/menu_wingrad.py      (from the repo root; needs the .sfc)
# (tools/setup.py runs it.)

ROM = _romlib.load("Chrono_Trigger_USA_SNES.sfc")

BASE = 0x3FBBF2                 # FF/BBF2 -- the first length byte
NLIST = 10                      # 0-5 = the six X-menu ribbon options; 6-9 follow (8 = the shop, screen $0C:
                                # --hdma on its open reads flat 8 / 32 / 112 / 64 / flat 8, and $7E:9D99 is
                                # written with FF/BC53's body by C2:F376 at the open). Past 9 the data is not a list.

lists, addrs = [], []
off = BASE
for i in range(NLIST):
    n = ROM[off]
    addrs.append(off + 1 - 0x3F0000)         # the FF/xxxx address of the list body
    lists.append(ROM[off + 1:off + 1 + n])
    off += 1 + n

PAIRS = ROM[0x28771:0x28771 + 0x20]      # C2/8771 -- the 16 (CGADSUB, COLDATA) pairs


def ramp(lst):
    """C2/86DD, transcribed: the window list -> a per-scanline signed 5-bit COLDATA delta."""
    out, acc = [], 0
    for i in range(0, len(lst), 2):
        kind = lst[i]
        if kind & 0x80:
            break                                # C2/871A BMI -- the list terminator is one byte
        h = lst[i + 1]
        if kind == 0:
            out += [0] * h                       # C2/875B: one flat entry, the neutral pair 02 E0
        else:
            step = h * 16                        # C2/8720: $A019 = height * 16
            for k in range(16):
                acc = (acc + step) & 0xFFFF      # C2/8733: $A01B += $A019
                out += [8 - k] * (acc >> 8)      # C2/873D: line count = the integer part
                acc &= 0x00FF                    # C2/8743: STZ $A01C -- keep the fraction
    return out


# The pair table has to decode to exactly the +8..-7 ramp the C side assumes (add 8..0, then sub 1..7).
for k in range(16):
    cgadsub, coldata = PAIRS[k * 2], PAIRS[k * 2 + 1]
    assert coldata & 0xE0 == 0xE0, "COLDATA must select all three channels"
    want = 8 - k
    got = (coldata & 0x1F) * (-1 if (cgadsub & 0x80) else 1)
    assert got == want, (k, got, want)

with open("src/data/menu_wingrad.h", "w") as f:
    f.write("// GENERATED by tools/gen/menu_wingrad.py -- do not edit.\n")
    f.write("// The menu WINDOW-GRADIENT lists, ROM $FF:BBF2 (length-prefixed, back to back), consumed by\n")
    f.write("// the HDMA-table generator C2/86DD. See the script header for the full derivation.\n")
    f.write("#ifndef CT_MENU_WINGRAD_H\n#define CT_MENU_WINGRAD_H\n#include <stdint.h>\n")
    f.write("// [kind, height] pairs, kind 0 = FLAT band / 1 = 16-step RAMP / 0x80 = end of list.\n")
    f.write("// Index 0-5 = the RIBBON OPTION (0 Status, 1 Item, 2 Tech, 3 Config, 4 Form, 5 Save); an\n")
    f.write("// ENTERED screen keeps the option's list (measured: entering never rewrites $7E:9D99).\n")
    f.write("// 6-9 are the lists that follow; 8 = the SHOP (screen $0C), measured on its open (--hdma bands\n")
    f.write("// flat 8 / 32 / 112 / 64 / flat 8; $7E:9D99 written with FF/BC53's body by C2:F376).\n")
    f.write("#define CT_MENU_WINLIST_N %d\n#define CT_MENU_WINLIST_SHOP 8\n" % NLIST)
    f.write("static const uint8_t ctMenuWinList[%d][16] = {\n" % NLIST)
    for i, l in enumerate(lists):
        body = ",".join("0x%02X" % b for b in l)
        pad = ",0x80" * (16 - len(l))
        f.write("  { %s%s },  // FF/%04X  %s\n" % (body, pad, addrs[i],
                                                   " ".join("%s%d" % ("flat" if l[j] == 0 else "RAMP", l[j + 1])
                                                            for j in range(0, len(l) - 1, 2))))
    f.write("};\n#endif\n")

print("wrote src/data/menu_wingrad.h")
for i, l in enumerate(lists):
    r = ramp(l)
    bands, y = [], 0
    while y < len(r):
        s = y
        while y < len(r) and r[y] == r[s]:
            y += 1
        bands.append("%d..%d:%+d" % (s, y - 1, r[s]))
    print("  list%d len=%2d rows=%3d  %s" % (i, len(l), len(r), " ".join(bands[:4]) + " ... " + bands[-1]))
