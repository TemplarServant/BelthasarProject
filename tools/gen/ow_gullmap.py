#!/usr/bin/env python3
"""src/data/ow_gullmap.h -- which slot of the gull atlas (CT_ASSET_WORLDSPR id 1) each ROM gull tile name is, matched
by pixels.

    python tools/gen/ow_gullmap.py [--capture] [--out PATH]

The anim sub-VM's op-4 descriptor names a 9-bit OBJ tile (C2/0D08 word2 bits0-8); the gull atlas is indexed by
capture order (`ct.exe --owbirds` keeps first sightings). Each name of the gull flap sequence C3:E6A2 (descriptors
E77A/E77F/E784 -> 1CA, 1CC, 1CE) is decoded from a live overworld state's VRAM (`--peek <w0> x --btnscript 0:40`) in
every OBJ palette and matched byte for byte against every atlas frame; the match must be unique (one palette, one slot
per tile), so a stale atlas or a wrong state fails loudly instead of baking a guess.

Default: the recipe ow_nav_w0 (it stands in for saves/ow_w0.state) and the atlas tools/gen/ow_sprites.py makes from it
(saves/ow_gulls.spr). --capture: saves/ow_w0.state and the shipped saves/ow_gulls.spr.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctgen import ROOT, recipe, peek, scratch, cgram_of  # noqa: E402
import ow_sprites  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'ow_gullmap.h')
NAMES = ow_sprites.GULL_NAMES


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--capture', action='store_true', help='read saves/ow_w0.state and saves/ow_gulls.spr')
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    os.environ.pop('CT_ORACLE_LOGICAL', None)          # the peek reads the plain oracle
    if a.capture:
        w0 = os.path.join(ROOT, 'saves', 'ow_w0.state')
        spr = open(os.path.join(ROOT, 'saves', 'ow_gulls.spr'), 'rb').read()
    else:
        w0 = recipe('ow_nav_w0')
        spr = ow_sprites.gulls(ow_sprites.ow_tool('--owbirds', w0, scratch('ow_birds')), w0)
    x = peek(w0, scratch('ow_gullpk'), '0:40', rule=False)
    vram, cg = open(x + '.raw.vram', 'rb').read(), ow_sprites.words(cgram_of(x + '.raw'))
    frames = [px for _, px in ow_sprites.spr_frames(spr)]

    hits = {}
    for pal in range(8):
        for nm in NAMES:
            dec = ow_sprites.decode16(vram, cg, nm, pal)
            for k, f in enumerate(frames):
                if f == dec:
                    hits.setdefault(nm, []).append((pal, k))
    missing = ['%03X' % nm for nm in NAMES if nm not in hits]
    if missing:
        sys.exit('ow_gullmap: no exact pixel match for tile(s) %s -- stale atlas, wrong state, or wrong palette'
                 % ', '.join(missing))
    for nm, hs in hits.items():
        if len(hs) != 1:
            sys.exit('ow_gullmap: tile %03X matched %d (palette, slot) pairs, expected exactly 1: %r' % (nm, len(hs), hs))
    pals = {h[0][0] for h in hits.values()}
    if len(pals) != 1:
        sys.exit('ow_gullmap: tiles matched under different palettes: %r' % pals)

    lines = [
        '// ow_gullmap.h - ROM tile name -> captured gull atlas slot, DERIVED BY PIXEL IDENTITY.',
        '// Generated by tools/_gen_owgullmap.py -- DO NOT EDIT BY HAND.',
        '//',
        "// The anim sub-VM's op-4 descriptor names a 9-bit OBJ tile (C2/0D08 word2 bits0-8); the",
        '// captured atlas is indexed by CAPTURE ORDER, which carries no ROM identity. Each tile below',
        "// was decoded from a live overworld state's VRAM with the gull's own palette (attr 0xBA ->",
        '// OBJ palette %d) and matched EXACTLY, byte for byte, against one atlas frame.' % pals.pop(),
        '// The generator asserts the match is unique, so a stale atlas fails loudly.',
        '#ifndef CT_OW_GULLMAP_H',
        '#define CT_OW_GULLMAP_H',
        '#include <stdint.h>',
        'typedef struct { uint16_t name; uint8_t slot; } CtOwGullFrame;',
        'static const CtOwGullFrame ctOwGullMap[] = {',
    ]
    lines += ['  { 0x%03X, %d },' % (nm, hits[nm][0][1]) for nm in NAMES]
    lines += ['};', '#define CT_OWGULLMAP_N %d' % len(NAMES), '#endif']
    with open(a.out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('ow_gullmap: %s -> %s' % (' '.join('%03X:#%d' % (nm, hits[nm][0][1]) for nm in NAMES), a.out))


if __name__ == '__main__':
    main()
