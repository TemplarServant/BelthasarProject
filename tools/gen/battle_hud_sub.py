#!/usr/bin/env python
"""Bake the battle Tech/Item SUBMENU chrome into src/data/battle_hud_sub.h from oracle captures.

WHAT THIS REPLACES. The first version of that header was ASSEMBLED out of the COMMAND phase's own
pixels (outer frames verbatim, interior cloned on its 32px period) with the window STRUCTURE read off
submenu captures that were believed to be hires/2x -- its own header said "the left window's right
frame at real x~124 = dump 248-249 dark dip". Measured against a proper capture, the Tech submenu's
window junction is at columns 172/175, not 124/127/128/131, and it is TWO dark columns, not four: the
assembled version put a whole extra frame pair 48 px to the left. The Item submenu is one unified
window on both.

CAPTURE RECIPE (both phases, BG1 only -- the strip chrome is 100% BG1, battle_hud_render.md Q2, so
this is the chrome with no text and no OBJ):

  PEEK_ISOBG=0 build/ct.exe --peek saves/gato_inbattle.state iso_tech.raw \
      --btnscript "0:600,20:2,0:20,100:2,0:60"                     # settle, Down to Tech, A
  PEEK_ISOBG=0 build/ct.exe --peek saves/gato_inbattle.state iso_item.raw \
      --btnscript "0:600,20:2,0:12,20:2,0:20,100:2,0:60"           # settle, Down x2 to Item, A

Both strips use ONLY colours already in ctBattleHudBg1Pal (checked here), so nothing about the
palette changes -- only the 48x256 index maps.

A THIRD capture is the TARGET-SELECT layout: the picker keeps the command boxes but box0 is
4 px narrower (dividers at 48/51 instead of 52/55, everything else identical), so it is its own
chrome and not the command bake.

  PEEK_ISOBG=0 build/ct.exe --peek saves/gato_inbattle.state iso_tgt.raw \n      --btnscript "0:600,100:2,0:20,100:2,0:200"        # settle, A on Att., A -> picker up

Usage: python tools/gen/battle_hud_sub.py [<iso_tech.raw> <iso_item.raw> <iso_tgt.raw> [out.h]]
With no captures named it makes the three itself from the recipe gato_inbattle (build/recipes/gato_inbattle.state,
CT_GEN_STATE overrides) with the scripts above.
"""
import io
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
STATE = (sys.argv[sys.argv.index('--state') + 1] if '--state' in sys.argv else os.environ.get('CT_GEN_STATE', os.path.join(ROOT, 'build', 'recipes', 'gato_inbattle.state')))
SP = os.environ.get('CT_SCRATCH', os.path.join(ROOT, 'build'))
CAPTURES = [('bhs_iso_tech.raw', '0:600,20:2,0:20,100:2,0:60'),
            ('bhs_iso_item.raw', '0:600,20:2,0:12,20:2,0:20,100:2,0:60'),
            ('bhs_iso_tgt.raw', '0:600,100:2,0:20,100:2,0:200')]


def capture():
    out = []
    for name, script in CAPTURES:
        p = os.path.join(SP, name)
        subprocess.run([os.path.join(ROOT, 'build', 'ct.exe'), '--peek', STATE, p, '--btnscript', script], cwd=ROOT,
                       env=dict(os.environ, PEEK_ISOBG='0'), check=True, stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL)
        out.append(p)
    return out

sys.path.insert(0, os.path.join(ROOT, 'tools'))
from ctlib import fb as F  # noqa: E402

STRIP_Y0, STRIP_H, OVERSCAN = 160, 48, 8


def palette():
    s = io.open(os.path.join(ROOT, "src", "data", "battle_hud.h"), encoding="utf-8", errors="ignore").read()
    i = s.index("ctBattleHudBg1Pal[62][3]")
    j = s.index("};", i)
    return [tuple(int(v) for v in m) for m in re.findall(r"\{(\d+),(\d+),(\d+)\}", s[i:j])]


def bake(path, pal):
    w, h, d = F.load(path)
    rows = []
    for ry in range(STRIP_H):
        y = STRIP_Y0 + ry + OVERSCAN
        row = []
        for x in range(256):
            k = ((y * w) + x) * 3
            c = (d[k], d[k + 1], d[k + 2])
            if c not in pal:
                raise SystemExit("colour %s at (%d,%d) is not in ctBattleHudBg1Pal" % (c, x, ry))
            row.append(pal.index(c))
        rows.append(row)
    return rows


def dark_columns(rows):
    """The window junction, for the record: columns whose mean is well below the strip median."""
    prof = [sum(rows[ry][x] for ry in range(8, 40)) // 32 for x in range(256)]
    med = sorted(prof)[128]
    return [x for x in range(256) if prof[x] < med - 12]


def main():
    args = sys.argv[1:] if len(sys.argv) >= 3 else capture()
    pal = palette()
    tech = bake(args[0], pal)
    item = bake(args[1], pal)
    tgt = bake(args[2], pal) if len(args) > 2 else None
    out = args[3] if len(args) > 3 else os.path.join(ROOT, "src", "data", "battle_hud_sub.h")
    print("tech junction columns:", dark_columns(tech))
    print("item junction columns:", dark_columns(item))
    if tgt: print("target-select junction columns:", dark_columns(tgt))

    L = []
    L.append("// Battle Tech/Item SUBMENU chrome -- CAPTURED from the oracle, BG1 only.")
    L.append("// GENERATED by tools/gen/battle_hud_sub.py -- see that file for the capture recipe.")
    L.append("// The strip chrome is 100% BG1 (battle_hud_render.md Q2), so a PEEK_ISOBG=0 capture of the")
    L.append("// open submenu IS the chrome: no text, no OBJ, nothing to subtract. Indices into")
    L.append("// ctBattleHudBg1Pal -- both phases use only colours it already has, so the palette is untouched.")
    L.append("// ⭐ WHAT THIS CORRECTED: the previous version was ASSEMBLED from the COMMAND phase's pixels,")
    L.append("// with the window structure read off captures believed to be hires/2x (\"the left window's")
    L.append("// right frame at real x~124 = dump 248-249 dark dip\"). The Tech submenu's junction is at")
    L.append("// columns 172/175 -- TWO dark columns -- not 124/127/128/131; the assembled version put a")
    L.append("// whole extra frame pair 48 px too far left. Item is one unified window on both.")
    L.append("#ifndef CT_BATTLE_HUD_SUB_H")
    L.append("#define CT_BATTLE_HUD_SUB_H")
    L.append("#include <stdint.h>")
    L.append("// ctBattleHudBg1Tgt: the TARGET-SELECT layout -- the command boxes with box0 4 px")
    L.append("// narrower (dividers at 48/51 against the command bake's 52/55, the rest identical).")
    sets = [("ctBattleHudBg1SubTech", tech), ("ctBattleHudBg1SubItem", item)]
    if tgt: sets.append(("ctBattleHudBg1Tgt", tgt))
    for name, rows in sets:
        L.append("static const uint8_t %s[%d][256] = {" % (name, STRIP_H))
        for r in rows:
            L.append("  {" + ",".join(str(v) for v in r) + "},")
        L.append("};")
    L.append("#endif")
    with io.open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
