#!/usr/bin/env python3
"""Regenerate src/data/menu_shop.h -- the Shop screen's ($0C) BG2 chrome, its narrow-digit tiles and text palettes.

Captured from the oracle, the way tools/gen/menu_chrome.py captures the Equip detail: open the shop from
the recipe menu_shop (loc 5, Crono under the fair merchant obj16, whose activate is `C8 90` = shop $10), dump VRAM and
read the BG2 tilemap at word 0x6000 (the menu's BG2 map, char base 0; --ppuregs on the open: BG2 map=6000 chr=0000).
The map is captured on the Buy/Sell screen, the Buy list and the quantity picker, and must be identical on all three
(the shop draws its windows once, C2/DACA's display list, and every later state writes BG1/BG3/OAM only) -- the
script asserts it. Only window tiles 0x3DC-0x3EF on palette 0 plus tile 0 appear, so the existing chrome tiles and
ctMenuChromePal[0] draw it; the per-window gradient is ctMenuWinList[CT_MENU_WINLIST_SHOP].

    python tools/gen/menu_shop.py                     the recipe menu_shop, under the rule
    python tools/gen/menu_shop.py --state <path>      any other start state (the owner's capture
                                                      saves/field_re/shop90_lake.state was taken without the rule:
                                                      add --norule); both give the tracked file byte for byte
Run from the repo root; needs the ROM + build/ct.exe.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctgen import ROOT, recipe, peek, scratch, cgram_of  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument('--state', help='start state (default: the recipe menu_shop)')
ap.add_argument('--norule', action='store_true', help='run the oracle without the rule (the private capture)')
ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'data', 'menu_shop.h'))
a = ap.parse_args()
STATE = a.state or recipe('menu_shop')

OPEN = '0:10,100:2,0:150'
DRIVES = [('main', OPEN, 162), ('buy', OPEN + ',100:2,0:40', 204), ('qty', OPEN + ',100:2,0:40,100:2,0:40', 246)]
TMW, TMH, BASE = 32, 28, 0x6000
maps, tiles, pals = [], [], []
for name, btn, fr in DRIVES:
    out = peek(STATE, scratch('menu_shop_' + name), btn, rule=not a.norule, frames=fr)
    v = open(out + '.raw.vram', 'rb').read()
    w = open(out + '.raw.wram', 'rb').read()
    if w[0x67] != 0x0C:
        sys.exit('menu_shop: the shop did not open ($0067 = %02X, not 0C)' % w[0x67])
    maps.append([v[BASE * 2 + i * 2] | (v[BASE * 2 + i * 2 + 1] << 8) for i in range(TMW * 64)])
    tiles.append(v[0x100 * 32:0x188 * 32])             # BG1 tiles 0x100-0x187 (chr base 0, 4bpp, 32 B each)
    pals.append(cgram_of(out + '.raw'))                # the --peek sidecar's CGRAM
assert maps[0] == maps[1] == maps[2], 'the shop chrome changed between its states'
assert tiles[0] == tiles[1] == tiles[2], 'the narrow-digit tiles changed between its states'
for p in range(8):
    assert pals[0][p * 32:p * 32 + 8] == pals[1][p * 32:p * 32 + 8] == pals[2][p * 32:p * 32 + 8]
T = tiles[0]
for t in range(0x88):                                  # 2bpp in a 4bpp tile: planes 2/3 must be empty
    assert not any(T[t * 32 + 16:t * 32 + 32]), 'tile %03X uses planes 2/3' % (0x100 + t)


def e5(c):
    return (c << 3) | (c >> 2)


def pal3(p):
    out = []
    for i in range(4):
        w = pals[0][p * 32 + i * 2] | (pals[0][p * 32 + i * 2 + 1] << 8)
        out.append((e5(w & 31), e5((w >> 5) & 31), e5((w >> 10) & 31)))
    return out


tm = maps[0][:TMW * TMH]
tq = maps[0][32 * TMW:(32 + TMH) * TMW]                # map rows 32-59: what BG2 V 255 shows (the equip sub-mode)
assert all(((e & 0x3FF) == 0 or 0x3DC <= (e & 0x3FF) <= 0x3EF) and ((e >> 10) & 7) == 0 for e in tm + tq)
with open(a.out, 'w', newline='\r\n') as f:
    # the first line names the script that first wrote the file; kept verbatim so the output stays the tracked bytes
    f.write('// GENERATED by tools/_gen_menuchrome_shop.py -- do not edit. The SHOP screen ($0C) BG2 chrome,\n')
    f.write('// captured from the oracle (VRAM word 0x6000) on its Buy/Sell, Buy-list and quantity states (identical).\n')
    f.write('#ifndef CT_MENU_SHOP_H\n#define CT_MENU_SHOP_H\n#include <stdint.h>\n')
    f.write('static const uint16_t ctMenuChromeShopTM[CT_MENU_CHROME_TMW*CT_MENU_CHROME_TMH] = {\n')
    for ty in range(TMH):
        f.write('  ' + ', '.join('0x%04X' % tm[ty * TMW + tx] for tx in range(TMW)) + ',\n')
    f.write('};\n')
    f.write('// Map rows 32-59 (the same capture): C2:C213 draws BOTH layouts into $7E:3E00 at init, and the equip sub-mode\n')
    f.write('// shows the second by BG2 V = $0D0A | $0D0B << 8 (C2/85D6): $0D0B = 00 (C2/E0DC) gives 255, i.e. line y + 256.\n')
    f.write('static const uint16_t ctMenuChromeShopEquipTM[CT_MENU_CHROME_TMW*CT_MENU_CHROME_TMH] = {\n')
    for ty in range(TMH):
        f.write('  ' + ', '.join('0x%04X' % tq[ty * TMW + tx] for tx in range(TMW)) + ',\n')
    f.write('};\n')
    f.write('// BG1 tiles 0x100-0x187 as the shop screen has them (2bpp in planes 0/1 of a 4bpp tile; 16 B each):\n')
    f.write('// the narrow one- and two-digit glyphs C2/DE56 composes the party panel numbers from (tile 0x16E + v/10,\n')
    f.write('// then 0x100 + v%100 or 0x164 + v). Their SOURCE is not derived (shop_screen.md 11.2) -- captured.\n')
    f.write('static const uint8_t ctShopNarrowTiles[0x88][16] = {\n')
    for t in range(0x88):
        f.write('  {' + ','.join('0x%02X' % b for b in T[t * 32:t * 32 + 16]) + '},\n')
    f.write('};\n')
    f.write('// BG palettes 0-7 (indices 0-3), CGRAM on the shop screen, (v<<3)|(v>>2): C2/DE62 picks 0 equal, 2 better,\n')
    f.write('// 7 worse for the panel numbers; C2/EC93 moves a dimmed member to (p & 3) | 4 (4 / 6 / 7), C2/A3ED dims to 7.\n')
    f.write('static const uint8_t ctShopTextPal[8][4][3] = {\n')
    for p in range(8):
        f.write('  {' + ','.join('{%d,%d,%d}' % c for c in pal3(p)) + '},\n')
    f.write('};\n#endif\n')
print('wrote', os.path.relpath(a.out, ROOT))
