# Extract the 8 CT character records for the new-game $7E:2600 init into a baked C header, so the runtime
# engine needs only ct_assets.dat (no .sfc). Two canonical sources, merged:
#   * bytes 0x00-0x35, 0x41-0x4F : ROM $CC:0000..0280 (file 0xC0000, 0x50/rec) -- the ROM char-base table
#       that C2/956E MVN-copies to $2600 (HP/MP/7 stats/LV/XP/equip/NEXT).
#   * bytes 0x36-0x40 : the DERIVED-stat block (effective stats + 0x3D ATK / 0x3E DEF), which the ROM base
#       leaves 0xFF and CT recomputes from the equipped gear. We take the oracle's post-recompute values
#       from the oracle in GATO's fight (the recipe gato_wait, tools/recipes/: its $2600 == the ROM base for every
#       char EXCEPT this block, so 0x36-0x40 there IS the canonical recalc of each char's join gear; the same 640
#       bytes as the capture gato_t0 this was first made from). Our equip is read-only, so these static derived
#       stats are exact; port the C2 recalc if equip-change is ever added.
import os as _ctos, sys as _ctsys
_ctsys.path.append(_ctos.path.normpath(_ctos.path.join(_ctos.path.dirname(_ctos.path.abspath(__file__)), '..')))
from ctlib import rom as _romlib  # the ROM through ctlib.rom: SHA-1 verified, a copier header stripped
import os
ROM=_romlib.load("Chrono_Trigger_USA_SNES.sfc")
def _wram(path):
    d=open(path,"rb").read()
    if len(d)==0x20000: return d
    pl=d[16:] if d[:4]==b"CTLS" else d          # tools/recipes.py wram_of: the LakeSnes state's WRAM at +69
    return pl[69:69+0x20000]
GATO=_wram(os.environ.get("CT_GEN_STATE","build/recipes/gato_wait.state"))
rec=bytearray(ROM[0xC0000:0xC0280])          # 8 x 0x50 ROM base
for cid in range(8):
    b=cid*0x50
    rec[b+0x36:b+0x41]=GATO[0x2600+b+0x36:0x2600+b+0x41]   # overlay the derived block 0x36..0x40
data=bytes(rec)
with open("src/data/ct_charbase.h","w") as f:
    f.write("// GENERATED by tools/gen/ct_charbase.py -- do not edit. The 8 CT character records copied to\n")
    f.write("// $7E:2600 by the new-game init (ROM C2/956E). Base 0x00-0x35/0x41-0x4F = ROM $CC:0000; the\n")
    f.write("// DERIVED block 0x36-0x40 (0x3D ATK / 0x3E DEF, recomputed from gear -- 0xFF in the ROM base)\n")
    f.write("// = the oracle's post-recalc values (gato_t0 $2600). Extracted once so the runtime needs only\n")
    f.write("// ct_assets.dat. Layout: +3 curHP,+5 maxHP,+7/+9 MP,+0B..11 stats,+12 LV,+13 XP,+27 helm,\n")
    f.write("// +28 armor,+29 weapon,+2A accessory,+2B NEXT,+3D ATK,+3E DEF.\n")
    f.write("#ifndef CT_CHARBASE_H\n#define CT_CHARBASE_H\n#include <stdint.h>\n")
    f.write("#define CT_CHARBASE_STRIDE 0x50\n#define CT_CHARBASE_COUNT 8\n")
    f.write("static const uint8_t ctCharBase[0x280] = {\n")
    for i in range(0,0x280,16):
        f.write("  "+",".join("0x%02X"%b for b in data[i:i+16])+",\n")
    f.write("};\n#endif\n")
# verify
for cid in range(3):
    b=cid*0x50
    print("char%d: LV=%d ATK(0x3D)=%d DEF(0x3E)=%d"%(cid,data[b+0x12],data[b+0x3D],data[b+0x3E]))
print("wrote src/data/ct_charbase.h")
