# Extract the menu's ROM data tables ONCE at build into a baked header, so the menu is fully ROM-free
# (runtime needs only ct_assets.dat). Raw contiguous regions (the engine keeps its CT-text decode):
#   CC 0x0C0B5E..0x0C257B : item names + single-tech names + tech MP
#   C2 0x02BD40..0x02C5B3 : per-char tech-id range + config cell-offset/value-base tables
#        (+ C2:C5A7, the button map's six row offsets in the $2E00 buffer, C2/C57A / C2/C5C7)
#   CFG 0x3FD3FE..0x3FD564 : config master string ptr table + its target strings ($FF/D462+)
#        (+ FF/D554, the button glyph words C2/C5B3 reads: A X L R B Y S; FF/D562, the bar icon per $0417, C2/C4BC)
#   MAXCNT 0x03FF951..0x03FF959 : per-char single-tech "add" threshold
# The item-category strings ($FF/B310 ptrs -> $FF-bank strings) are scattered ROM-wide, so we RESOLVE
# them here into a per-item decoded table (ctItemCat) instead of baking the whole bank.
ROM=open("Chrono_Trigger_USA_SNES.sfc","rb").read()
def region(lo,hi): return ROM[lo:hi]
CC=(0x0C0B5E,0x0C257B); C2=(0x02BD40,0x02C5B3); CFG=(0x3FD3FE,0x3FD57A); MC=(0x03FF951,0x03FF959)
# Config screen (menu screen 4), derived in disasm/notes/menu2_config_toggles.md:
#   NAV  FF/B5A0 : the 21-cell cursor graph, 6 bytes per cell [x, y, up, down, left, right].
#        The screen builder C2/C3B5 copies it verbatim to $7E:9380 and C2/E9E2 walks it; the
#        first two bytes are the hand sprite position (C2/E964 LDA $9380,X / STA $0770).
#   CDEF C2/FCA6 : the NEW-GAME config defaults -- 12 bytes MVNd to $2990 by C2/95D4..C2/960A.
#        [0..2] = the packed config $2990/$2991/$2992, [3..11] = the live button map $2993..$299B
#        (the same 9 bytes are MVNd to $0408 from C2/FCA9, i.e. this block overlaps at +3).
NAV=(0x3FB5A0,0x3FB5A0+21*6); CDEF=(0x02FCA6,0x02FCA6+12)
def catname(idv):
    pe=0x3FB310+idv*2; p=ROM[pe]|(ROM[pe+1]<<8); so=0x3F0000+p; s=""
    for i in range(16):
        c=ROM[so+i]
        if c==0: break
        if   0xA0<=c<=0xB9: s+=chr(ord('A')+c-0xA0)
        elif 0xBA<=c<=0xD3: s+=chr(ord('a')+c-0xBA)
        elif 0xD4<=c<=0xDD: s+=chr(ord('0')+c-0xD4)
        elif c in (0xEF,0xFF): s+=' '
    return s.strip()
def emit(f,name,data,base=None):
    if base is not None: f.write("#define %s_BASE 0x%06Xu\n"%(name.upper(),base))
    f.write("static const uint8_t %s[%d] = {\n"%(name,len(data)))
    for i in range(0,len(data),16): f.write("  "+",".join("0x%02X"%b for b in data[i:i+16])+",\n")
    f.write("};\n")
with open("src/data/menu_romdata.h","w") as f:
    f.write("// GENERATED by tools/gen/menu_romdata.py -- do not edit. The menu's ROM data tables, extracted\n")
    f.write("// once so the runtime menu needs no .sfc (RE re-impl, not emulation). See the script header.\n")
    f.write("#ifndef CT_MENU_ROMDATA_H\n#define CT_MENU_ROMDATA_H\n#include <stdint.h>\n")
    emit(f,"ctRomCC",region(*CC),CC[0])
    emit(f,"ctRomC2",region(*C2),C2[0])
    emit(f,"ctRomCfg",region(*CFG),CFG[0])
    emit(f,"ctRomMaxCnt",region(*MC),MC[0])
    f.write("// FF/B53E -- the ITEM screen's cursor graph, 15 records x 6 bytes, copied verbatim to $7E:9380 by the\n")
    f.write("// screen builder exactly as FF/B5A0 (below) is on Config. Records 0..9 are the ten list rows at\n")
    f.write("// (24, 87 + 12*row), 10/11 the Use/Move labels, 12..14 the target-select party cells; bytes +2..+5 are\n")
    f.write("// the Up/Down/Left/Right neighbours. VERIFIED byte-identical to the oracle's live $7E:9380 on its own\n")
    f.write("// Item-screen capture, whose cursor OAM $0770 = (0x18, 0x57) = record 0.\n")
    f.write("#define CTITEMNAV_BASE 0x3FB53Eu\n")
    emit(f,"ctItemNav",region(0x3FB53E,0x3FB53E+15*6))
    emit(f,"ctCfgNav",region(*NAV),NAV[0])
    emit(f,"ctCfgDefaults",region(*CDEF),CDEF[0])
    f.write("// FF/C9FC -- sixteen 2bpp tiles the menu's graphics build C2/968D DMAs (C2/9542) over tiles 0x30-0x3F of\n")
    f.write("// its font copy at $7E:5000 (FF/8E60 = FF/8C60's tile 0x20 on): 0x30 #, 0x31 the arrow, 0x32-0x34 frame/+,\n")
    f.write("// 0x35-0x3F bold letters. Measured: the oracle's menu VRAM holds them at BG3 $E000 and BG1 4bpp tile 0x30+.\n")
    emit(f,"ctMenuFontC9FC",region(0x3FC9FC,0x3FC9FC+0x100),0x3FC9FC)
    # resolved per-item category (fixed 12-byte, NUL-padded ASCII)
    f.write("static const char ctItemCat[256][12] = {\n")
    for idv in range(256):
        s=catname(idv)[:11]
        f.write('  "%s",\n'%s.replace('"','\\"'))
    f.write("};\n#endif\n")
print("wrote src/data/menu_romdata.h  (CC %d, C2 %d, CFG %d, MAXCNT %d, NAV %d, CDEF %d bytes + 256 cats)"%(
    CC[1]-CC[0],C2[1]-C2[0],CFG[1]-CFG[0],MC[1]-MC[0],NAV[1]-NAV[0],CDEF[1]-CDEF[0]))
print("  cfg nav cell0:",region(*NAV)[:6].hex(" "),"(expect 08 1b 04 01 05 05)")
print("  cfg defaults :",region(*CDEF).hex(" "),"(expect 84 a0 01 80 08 40 08 02 04 10 20 40)")
# sanity: a few known decodes
print("  item 0xD6:",repr(catname(0xD6)),"(expect ITEM)")
