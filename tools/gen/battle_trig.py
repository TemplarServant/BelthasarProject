#!/usr/bin/env python3
"""Bake the battle-movement TRIG tables into src/data/battle_trig.h.

Derivation dossier: disasm/notes/battle_enemy_move_target.md §A + the Wave-2 ADDENDUM,
plus the STEP-2 disasm working notes. The enemy field-movement mover (CF/F98F), the angle
computation (atan2 C1/0222) and the per-segment sin/cos step (C1/01F9) all index three raw
ROM tables in bank C0. This generator copies them BYTE-FOR-BYTE from the ROM (the sanctioned
bake method -- nothing computed/approximated) and emits them as C arrays:

  * C0/F300 -> ctBattleAtanTab[1024]  -- the ARCTANGENT table (C1/0222 `LDA $C0F300,X`).
      32x32: index = (|dy|>>3)*32 + (|dx|>>3); the byte is atan(|dy|/|dx|) in the FIRST octant
      where 0x40 == 90deg (a full turn == 0x100). C1/0222 folds the quadrant from the dx/dy signs.
  * C0/F900 -> ctBattleSinTab[1024]   -- the SINE table (CF/F9FB / C1/01F9 `LDA $C0F900,X`).
      Indexed (angle<<2)&0x3FF; the byte is |255*sin(angle*360/256deg)|, and the reader NEGATES
      it when the index >= 0x200 (the lower half-turn) -> a signed sine in [-255,+255]. cos(a) is
      read as sin(a+0x40).
  * C0/F700 -> ctBattleFaceTab[1024] -- the FACING/octant table (C1/379A:37E9 `LDA $C0F700,X`,
      indexed by the raw angle) used to pick the sprite's walk facing. Baked for completeness
      (the walk-pose facing, E.6); the POSITION math needs only F300+F900.

Run from repo root (needs Chrono_Trigger_USA_SNES.sfc in cwd). Emits src/data/battle_trig.h.
--verify re-reads the ROM and spot-checks a handful of table entries + the derived sin/atan2.
"""
import os, sys

ROM = os.environ.get('CT_ROM', 'Chrono_Trigger_USA_SNES.sfc')
OUT_H = 'src/data/battle_trig.h'

# HiROM: file offset == the bank-C0 CPU offset for bank C0 (dis.py convention).
TAB = [('ctBattleAtanTab', 0xF300, 'C0/F300 arctangent (C1/0222)'),
       ('ctBattleSinTab',  0xF900, 'C0/F900 sine, signed-when-idx>=0x200 (CF/F9FB, C1/01F9)'),
       ('ctBattleFaceTab', 0xF700, 'C0/F700 facing/octant (C1/379A)')]
NBYTE = 0x400


def emit_array(rom, name, off, note):
    b = rom[off:off + NBYTE]
    out = ['// %s -- %d bytes copied verbatim from ROM file 0x%05X.' % (note, NBYTE, off),
           'static const unsigned char %s[%d] = {' % (name, NBYTE)]
    for i in range(0, NBYTE, 16):
        out.append('  ' + ','.join('0x%02X' % x for x in b[i:i + 16]) + ',')
    out.append('};')
    return '\n'.join(out)


def main():
    rom = open(ROM, 'rb').read()
    if '--verify' in sys.argv:
        # spot-check the SINE reader (signed) reproduces the physics we validated (angle 0x40 == +255 == +Y).
        def sin_signed(a):
            idx = (a << 2) & 0x3FF
            t = rom[0xF900 + idx]
            return -t if idx >= 0x200 else t
        assert sin_signed(0x00) == 0, sin_signed(0x00)
        assert sin_signed(0x40) == 255, sin_signed(0x40)    # +90deg -> +255 (mover +Y)
        assert sin_signed(0x80) == 0, sin_signed(0x80)
        assert sin_signed(0xC0) == -255, sin_signed(0xC0)   # +270deg -> -255 (mover -Y)
        # atan2 first-octant sentinels
        assert rom[0xF300 + 0] == 0x40                       # atan(0/0) sentinel = 90deg
        assert rom[0xF300 + 1 * 32 + 0] == 0x40              # dx=0 -> 90deg
        assert rom[0xF300 + 0 * 32 + 5] == 0x00              # dy=0 -> 0deg
        print('battletrig --verify OK: sin(0/40/80/C0)=0/255/0/-255; atan sentinels 0x40/0x40/0x00')
        return
    parts = ['// AUTO-GENERATED by tools/gen/battle_trig.py -- DO NOT EDIT. See that file for the derivation.',
             '// Battle enemy-movement trig tables (disasm/notes/battle_enemy_move_target.md).',
             '#ifndef CT_BATTLE_TRIG_H', '#define CT_BATTLE_TRIG_H', '']
    for name, off, note in TAB:
        parts.append(emit_array(rom, name, off, note))
        parts.append('')
    parts.append('#endif')
    with open(OUT_H, 'w') as f:
        f.write('\n'.join(parts) + '\n')
    print('wrote %s (%d tables x %d bytes)' % (OUT_H, len(TAB), NBYTE))


if __name__ == '__main__':
    main()
