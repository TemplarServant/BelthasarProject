#!/usr/bin/env python3
"""Splice a snes9x (#!s9xsnp:0011) state's WRAM + CPU registers into a LakeSnes
state generated by `ct.exe` (e.g. via --teleport to the same scene), producing a
LakeSnes state the oracle can load and run. The base supplies valid field-mode
PPU/APU/DMA/cart; we overwrite the WRAM and the CPU register file with the
snes9x state's, so the CPU resumes consistently with the demo's stack/WRAM.

Output is always CTLS-wrapped (magic + version + length + CRC-32 of the raw
handleState payload) so a truncated or bit-rotted file cannot load as silent
garbage. The base may be CTLS or legacy raw; both are accepted.

LakeSnes payload layout (snes_handleState):
  off 69          : WRAM byte array, 0x20000
  payload tail    : cart_handleState = the cart's SRAM (CT: 8 KB) -- the last block written
  off 69+0x20000  : cpu_handleState = 15 bools + 2 bytes(k,db) + 6 words(a,x,y,sp,pc,dp)
                    bools order: c z v n i d xf mf e waiting stopped irqWanted nmiWanted intWanted resetWanted
                    words are little-endian.
snes9x REG block (16 B, big-endian pairs): PB DB P A D S X Y PCw.

Usage: python tools/s9x_to_lake.py <s9x.state> <base_lake.state> <out_lake.state> [--ppu]

--ppu also splices the snes9x state's VRAM (the VRA block), OAM and CGRAM (the PPU block) over the base's: without it
the picture keeps the base state's tiles and palettes until the game re-uploads them (a battle capture then draws
another fight's enemy tiles).
The base's own copies are located by their bytes (a --peek of 0 frames dumps them) and replaced in place; the PPU's
registers stay the base's, so use a base in the same mode (a battle base for a battle capture).
"""
import os
import sys
import gzip

# Allow `python tools/s9x_to_lake.py` without installing the package.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctlib import lake  # noqa: E402

WRAM_OFF = lake.WRAM_OFF
CPU_OFF = lake.CPU_OFF
CART_SRAM_SIZE = 0x2000   # CT ships 8 KB of cart SRAM; cart_handleState writes it last


def split_blocks(raw):
    assert raw[:13] == b"#!s9xsnp:0011", raw[:13]
    i = raw.index(b"\n") + 1
    blocks = {}
    while i + 11 <= len(raw):
        name = raw[i:i + 3]
        if raw[i + 3:i + 4] != b":":
            break
        size = int(raw[i + 4:i + 10])
        blocks[name.decode("latin1")] = raw[i + 11:i + 11 + size]
        i += 11 + size
    return blocks


def be(b):
    v = 0
    for x in b:
        v = (v << 8) | x
    return v


def splice_ppu(s9x_path, out_path):
    """VRAM, OAM and CGRAM of the snes9x state over the lake state at out_path (see --ppu in the docstring)."""
    import struct
    import subprocess
    from ctlib import s9x as s9
    pp = s9.ppu(s9x_path)["ppu"]
    vram_new = bytes(s9.split_blocks(s9x_path)["VRA"])
    oam_new = bytes(pp["oamData"])
    cg_new = b"".join(struct.pack("<H", w & 0x7FFF) for w in pp["cgdata"])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    probe = os.path.join(root, "build", "_s9x_ppu_probe.raw")
    subprocess.run([os.path.join(root, "build", "ct.exe"), "--peek", out_path, probe, "--btnscript", "0:0"],
                   capture_output=True)
    vram_old = open(probe + ".vram", "rb").read()
    side = open(probe + ".oam", "rb").read()                     # OAM 544 B ... CGRAM 512 B at the tail
    payload, _fmt = lake.read_payload(out_path)
    st = bytearray(payload)
    for name, old, new in (("VRAM", vram_old, vram_new), ("OAM", side[:544], oam_new), ("CGRAM", side[-512:], cg_new)):
        i = st.find(old)
        assert len(old) == len(new) and i >= 0 and st.find(old, i + 1) < 0, name + ": not found exactly once in the base"
        st[i:i + len(new)] = new
        print("%s spliced at payload +%d (%d B)" % (name, i, len(new)))
    lake.write_wrapped(out_path, bytes(st))
    for ext in ("", ".oam", ".vram", ".wram"):
        try:
            os.remove(probe + ext)
        except OSError:
            pass

def main():
    s9x_path, base_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    raw = open(s9x_path, "rb").read()
    raw = gzip.decompress(raw) if raw[:2] == bytes([0x1f, 0x8b]) else raw
    blk = split_blocks(raw)
    wram = blk["RAM"]
    assert len(wram) >= 0x20000, len(wram)
    reg = blk["REG"]
    assert len(reg) == 16, len(reg)
    # decode REG (big-endian pairs): PB DB P A D S X Y PCw
    PB = reg[0]
    DB = reg[1]
    P = be(reg[2:4]) & 0xFF
    A = be(reg[4:6])
    D = be(reg[6:8])
    S = be(reg[8:10])
    X = be(reg[10:12])
    Y = be(reg[12:14])
    PC = be(reg[14:16])
    print("REG: PB=%02X DB=%02X P=%02X A=%04X D=%04X S=%04X X=%04X Y=%04X PC=%04X"
          % (PB, DB, P, A, D, S, X, Y, PC))
    # P flag bits -> LakeSnes bools
    c = P & 1
    z = (P >> 1) & 1
    i_ = (P >> 2) & 1
    d = (P >> 3) & 1
    xf = (P >> 4) & 1
    mf = (P >> 5) & 1
    v = (P >> 6) & 1
    n = (P >> 7) & 1
    e = 0  # field engine is native mode
    bools = [c, z, v, n, i_, d, xf, mf, e, 0, 0, 0, 0, 0, 0]  # +waiting/stopped/*Wanted=0
    cpu = bytearray()
    cpu += bytes(bools)
    cpu += bytes([PB & 0xFF, DB & 0xFF])
    for w in (A, X, Y, S, PC, D):  # a x y sp pc dp, little-endian
        cpu += bytes([w & 0xFF, (w >> 8) & 0xFF])
    assert len(cpu) == 29, len(cpu)

    base_payload, base_fmt = lake.read_payload(base_path)
    st = bytearray(base_payload)
    st[WRAM_OFF:WRAM_OFF + 0x20000] = wram[:0x20000]
    st[CPU_OFF:CPU_OFF + 29] = cpu

    # Cart SRAM too, when the snes9x state carries one. cart_handleState is the last block written
    # by snes_handleState, so the cart's 8 KB of SRAM occupies the payload's tail. Without this the
    # spliced state silently inherits the base state's SRAM (e.g. empty save slots, $0D49 = 000000).
    sram_note = "no SRA block"
    sra = blk.get("SRA")
    if sra:
        n = CART_SRAM_SIZE
        st[len(st) - n:] = sra[:n]
        used = [k for k in range(3)
                if (sra[(0x7FF8 + k * 2) & (n - 1)] | (sra[(0x7FF9 + k * 2) & (n - 1)] << 8)) == 0xE41B]
        sram_note = "SRAM %d B spliced, used slots %s" % (n, used if used else "none")
    out_size = lake.write_wrapped(out_path, bytes(st))
    loc = wram[0x100] | (wram[0x101] << 8)
    print("spliced WRAM(loc=%03X) + CPU into %s (CTLS %d B, payload %d B; base was %s; %s)"
          % (loc, out_path, out_size, len(st), base_fmt, sram_note))
    if "--ppu" in sys.argv[4:]:
        splice_ppu(s9x_path, out_path)


if __name__ == "__main__":
    main()
